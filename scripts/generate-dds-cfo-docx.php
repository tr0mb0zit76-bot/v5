/**
 * @param  list<list<string>>  $rows
 */
function addTable(Section $section, array $rows): void
{
    $colCount = max(count($rows[0] ?? []), 1);
    $table = $section->addTable([
        'borderSize' => 6,
        'borderColor' => '999999',
        'cellMargin' => 60,
        'width' => 9000,
        'unit' => TblWidth::TWIP,
    ]);
    foreach ($rows as $ri => $row) {
        $table->addRow();
        foreach ($row as $cell) {
            $c = $table->addCell((int) (9000 / $colCount), $ri === 0 ? ['bgColor' => 'E8EEF5'] : []);
            $c->addText((string) $cell, [
                'bold' => $ri === 0,
                'size' => 10,
                'name' => 'Times New Roman',
            ]);
        }
    }
    $section->addTextBreak(0);
}
